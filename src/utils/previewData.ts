function makeToyThumbSvg(label: string, bg: string, accent: string): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="240" height="240" viewBox="0 0 240 240">
    <rect width="240" height="240" rx="20" fill="${bg}"/>
    <rect x="44" y="62" width="152" height="116" rx="16" fill="${accent}" opacity="0.16"/>
    <circle cx="96" cy="120" r="24" fill="${accent}"/>
    <rect x="132" y="96" width="44" height="48" rx="8" fill="${accent}" opacity="0.82"/>
    <text x="120" y="210" font-family="system-ui, sans-serif" font-size="16" font-weight="600" fill="#1e293b" text-anchor="middle">${label}</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

